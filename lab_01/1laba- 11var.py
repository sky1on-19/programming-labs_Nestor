print("Расход житкости в трубе: Q = S * v(S = pi * d**2/4)")
print("Введите значение pi: ")
pi = float(input())
print("Введите значение d: ")
d = float(input())
print("Введите значение v: ")
v = float(input())
#Вводится значение каждой переменной, у которой есть плавающая точка
S = pi * d**2 / 4
Q =  '{0:.4f}'.format(S * v, 4)#Оставляет только 4 цифры после запятой
print("Расход житкости в трубе, при заданных условиях составляет: ", Q)